#!/usr/bin/env bash
# ── Build the 3D views (crates/skill-viz3d, on threers) for the web view ─────
#
# Usage:
#   bash scripts/build-viz3d.sh            # release: size-optimised, wasm-opt
#   bash scripts/build-viz3d.sh --dev      # debug build, no wasm-opt (fast)
#
# Output: src/lib/viz3d/pkg/ (skill_viz3d.js, skill_viz3d.d.ts,
# skill_viz3d_bg.wasm), imported by src/lib/viz3d/index.ts.  Skipped when the
# crate's sources are older than the output, unless VIZ3D_FORCE=1.
#
# Needs: rustup target wasm32-unknown-unknown, and wasm-bindgen-cli at the
# exact wasm-bindgen version in crates/skill-viz3d/Cargo.lock (checked below).
# wasm-opt (binaryen) is used when on PATH.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
CRATE="$ROOT/crates/skill-viz3d"
OUT="$ROOT/src/lib/viz3d/pkg"

PROFILE="release-wasm"
if [[ "${1:-}" == "--dev" ]]; then
  PROFILE="dev"
fi

if [[ "${VIZ3D_FORCE:-0}" != "1" && -f "$OUT/skill_viz3d_bg.wasm" ]]; then
  newer="$(find "$CRATE/src" "$CRATE/Cargo.toml" "$CRATE/Cargo.lock" -newer "$OUT/skill_viz3d_bg.wasm" 2>/dev/null | head -1)"
  if [[ -z "$newer" ]]; then
    echo "viz3d: up to date ($OUT)"
    exit 0
  fi
fi

if ! rustup target list --installed 2>/dev/null | grep -qx wasm32-unknown-unknown; then
  echo "error: rustup target add wasm32-unknown-unknown" >&2
  exit 1
fi

# wasm-bindgen's CLI must match the crate exactly, or the build fails only at
# the end with a schema-version error.
want="$(awk '/^name = "wasm-bindgen"$/ { getline; gsub(/"/, "", $3); print $3; exit }' "$CRATE/Cargo.lock" 2>/dev/null || true)"
have="$(wasm-bindgen --version 2>/dev/null | awk '{ print $2 }' || true)"
if [[ -n "$want" && "$have" != "$want" ]]; then
  echo "error: wasm-bindgen-cli $want needed (found: ${have:-none}):" >&2
  echo "  cargo install wasm-bindgen-cli --version $want --locked" >&2
  exit 1
fi

# Where cargo actually writes: skill's .cargo/config.toml points every build
# at src-tauri/target, this crate's included.
TARGET_DIR="$(cd "$CRATE" && cargo metadata --format-version 1 --no-deps | sed -E 's/.*"target_directory":"([^"]+)".*/\1/')"
# Leave threers' own JS bindings out: this crate exports its own, and
# exports are roots that nothing prunes.
export RUSTFLAGS="${RUSTFLAGS:-} --cfg threers_no_js_bindings"

echo "viz3d: cargo build ($PROFILE, wasm32)…"
(cd "$CRATE" && cargo build --target wasm32-unknown-unknown --lib --profile "$PROFILE")

dir="$PROFILE"
[[ "$PROFILE" == "dev" ]] && dir="debug"
mkdir -p "$OUT"
wasm-bindgen "$TARGET_DIR/wasm32-unknown-unknown/$dir/skill_viz3d.wasm" \
  --target web --out-dir "$OUT" --remove-producers-section

# Generated glue: typed by its .d.ts, not checked as source (tsconfig has
# checkJs on, and an imported file is checked whatever `exclude` says).
glue="$OUT/skill_viz3d.js"
{ echo "// @ts-nocheck — generated by wasm-bindgen (scripts/build-viz3d.sh)"; cat "$glue"; } > "$glue.tmp"
mv "$glue.tmp" "$glue"

if [[ "$PROFILE" != "dev" ]] && command -v wasm-opt >/dev/null 2>&1; then
  echo "viz3d: wasm-opt -Oz…"
  # The --enable flags match what wasm-bindgen's output uses.
  wasm-opt -Oz --enable-bulk-memory --enable-nontrapping-float-to-int \
    --enable-sign-ext --enable-mutable-globals --enable-reference-types \
    --enable-multivalue \
    "$OUT/skill_viz3d_bg.wasm" -o "$OUT/skill_viz3d_bg.wasm.opt"
  mv "$OUT/skill_viz3d_bg.wasm.opt" "$OUT/skill_viz3d_bg.wasm"
fi

size="$(wc -c < "$OUT/skill_viz3d_bg.wasm" | tr -d ' ')"
echo "viz3d: $OUT/skill_viz3d_bg.wasm ($((size / 1024)) KiB)"
